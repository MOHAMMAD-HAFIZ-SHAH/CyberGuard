
from typing import Any


def generate_report(
    title: str,
    description: str,
    evidence: list[dict],
    hypotheses: list[dict],
    crewai_analysis: dict[str, Any] | None = None,
) -> str:
    """
    Generate one CyberGuard investigation report.

    Existing evidence and hypotheses are reported first. When available,
    CrewAI's analysis is incorporated into the same report as an
    explicitly labeled, AI-generated interpretation.

    This function does not treat AI analysis as verified forensic fact.
    """

    lines = [
        "CYBERGUARD INVESTIGATION REPORT",
        "=" * 36,
        f"Incident: {title}",
        f"Description: {description}",
        "",
        "1. EVIDENCE",
    ]

    if not evidence:
        lines.append(
            "No recognized events or evidence records were supplied."
        )

    for item in evidence:
        if not isinstance(item, dict):
            continue

        evidence_id = item.get("evidence_id", "Unknown ID")
        timestamp = item.get("timestamp") or "Time unknown"
        event_type = item.get("event_type", "unknown")
        severity = item.get("severity", "unknown")
        source = item.get("source", "Unknown source")
        item_description = item.get("description", "")

        lines.append(
            f"{evidence_id} | {timestamp} | {event_type} | "
            f"{severity} | {source} | {item_description}"
        )

    lines.extend(["", "2. HYPOTHESES"])

    if not hypotheses:
        lines.append(
            "No hypotheses were generated by the existing "
            "rule-based hypothesis agent."
        )

    for item in hypotheses:
        if not isinstance(item, dict):
            continue

        hypothesis_id = item.get("hypothesis_id", "Unknown ID")
        hypothesis_description = item.get(
            "description",
            "No description provided.",
        )
        status = item.get("status", "requires_review")

        confidence = item.get("confidence")
        if isinstance(confidence, (int, float)):
            confidence_text = f"{confidence:.0%}"
        else:
            confidence_text = "Unavailable"

        supporting = item.get("supporting_evidence", [])
        contradicting = item.get("contradicting_evidence", [])

        if not isinstance(supporting, list):
            supporting = []

        if not isinstance(contradicting, list):
            contradicting = []

        lines.extend([
            f"{hypothesis_id}: {hypothesis_description}",
            f"Status: {status}",
            f"Heuristic score: {confidence_text}",
            "Supporting evidence: "
            + (", ".join(str(value) for value in supporting) or "None"),
            "Contradicting evidence: "
            + (
                ", ".join(str(value) for value in contradicting)
                or "None"
            ),
            "",
        ])

    # Include CrewAI's analysis in this same report.
    # Accept either the complete result dictionary or a plain string.
    if isinstance(crewai_analysis, dict):
        crew_status = crewai_analysis.get("status", "unknown")
        analysis_text = str(
            crewai_analysis.get("analysis")
            or crewai_analysis.get("review")
            or ""
        ).strip()
    elif isinstance(crewai_analysis, str):
        crew_status = "completed" if crewai_analysis.strip() else "skipped"
        analysis_text = crewai_analysis.strip()
    else:
        crew_status = "skipped"
        analysis_text = ""

    lines.extend([
        "3. AI-ASSISTED EVIDENCE ANALYSIS",
        "-" * 36,
    ])

    if crew_status == "completed" and analysis_text:
        lines.extend([
            "The following analysis was generated by CrewAI.",
            "It is an interpretation of the supplied evidence, "
            "not an independently verified forensic conclusion.",
            "",
            analysis_text,
            "",
        ])
    elif crew_status == "failed":
        lines.extend([
            "CrewAI analysis was unavailable because the AI review failed.",
            "The evidence and existing hypothesis results are retained.",
            "",
        ])
    else:
        lines.extend([
            "No CrewAI analysis was available for this investigation.",
            "",
        ])

    lines.extend([
        "4. LIMITATIONS",
        "This report is based on the evidence supplied to CyberGuard.",
        "Heuristic scores are not calibrated probabilities.",
        "AI-generated interpretations are not verified forensic facts.",
        "Evidence references do not independently prove a hypothesis.",
        "Missing evidence does not prove that an incident did not occur.",
        "Review timestamps, source context, and alternative explanations.",
        "A qualified analyst should validate findings before taking action.",
        "Preserve original evidence and document any further examination.",
    ])

    return "\n".join(lines)
